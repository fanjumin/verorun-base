def extract_underscore_calls(file_path):
    """Extract strings from _('...') or _(\"...\") calls only."""
    strings = set()
    with open(file_path, 'r', encoding='utf-8', errors='replace') as f:
        content = f.read()
    matches = re.findall(r"_\s*\(\s*(['\"])(.+?)\1\s*\)", content)
    for quote, text in matches:
        text = text.strip()
        if text and len(text) < 500:
            strings.add(text)
    return strings


